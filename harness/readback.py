"""Turn validated commands back into ATC-style phrasing.

Generated by Python from the SAME objects that will execute, never by the model,
so what the user confirms is exactly what will happen.
"""

from harness.schema import Clarify, CommandBatch, SetAirspeed, SetAltitude, SetFrequency, SetHeading
from harness.state import AircraftState


def readback(batch: CommandBatch, state: AircraftState) -> str:
    return ", ".join(_phrase(cmd, state) for cmd in batch.commands)


def _phrase(cmd, state: AircraftState) -> str:
    match cmd:
        case SetAltitude():
            if cmd.altitude_ft > state.altitude_ft:
                verb = "climb and maintain"
            elif cmd.altitude_ft < state.altitude_ft:
                verb = "descend and maintain"
            else:
                verb = "maintain"
            return f"{verb} {cmd.altitude_ft:,} feet"
        case SetHeading():
            turn = f"turn {cmd.turn_direction}" if cmd.turn_direction else "fly"
            return f"{turn} heading {cmd.heading_deg:03d}"
        case SetAirspeed():
            return f"maintain {cmd.airspeed_kt} knots"
        case SetFrequency():
            return f"tune {cmd.radio} {cmd.frequency_mhz:.3f}"
        case Clarify():
            return f"unable, {cmd.question}"
    return f"unknown command {cmd!r}"
